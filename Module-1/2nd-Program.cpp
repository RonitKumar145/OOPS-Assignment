#include <iostream>
#include <string>
using namespace std;

int main() {
    // Demonstrating various data types
    int age = 21;
    cout << "int value = " << age << endl;
    cout << "int size = " << sizeof(int) << " Bytes" << endl;

    char grade = 'A';
    cout << "char value = " << grade << endl;
    cout << "char size = " << sizeof(char) << " Bytes" << endl;

    float salary = 20000.11f;
    cout << "float value = " << salary << endl;
    cout << "float size = " << sizeof(float) << " Bytes" << endl;

    double balance = 150.116;
    cout << "double value = " << balance << endl;
    cout << "double size = " << sizeof(double) << " Bytes" << endl;

    bool isStudent = true;
    cout << "boolean value = " << isStudent << endl;
    cout << "boolean size = " << sizeof(bool) << " Bytes" << endl;

    string name = "Ronit";
    cout << "string value = " << name << endl;
    cout << "string size = " << sizeof(string) << " Bytes" << endl;

    return 0;
}
