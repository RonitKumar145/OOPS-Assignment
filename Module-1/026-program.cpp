#include <iostream>
using namespace std;

int main() {
    int n;
    cout << "Enter the limit for the series: ";
    cin >> n;

    cout << "Series using for loop: ";
    // loop from i = 1 to n
    for (int i = 1; i <= n; i++) {
        cout << i << " ";
    }
    cout << endl;

    return 0;
}
