#include <iostream>
using namespace std;

int main() {
    // Type Casting Demonstration
    float decimalNum = 10.5;

    // Explicit conversion from float to int
    int integerNum = (int)decimalNum;

    cout << "Decimal number: " << decimalNum << endl;
    cout << "After type casting to int: " << integerNum << endl;

    return 0;
}
